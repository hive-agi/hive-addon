(def ^:private NsName
  "Dotted, hyphenated namespace names, which is what reaches ns->base-path.
   Generated by joining lower-case segments drawn from a fixed alphabet, so no
   regex generator is needed."
  [:string {:min 1
            :gen/fmap #(str/join "." (map str/join %))
            :gen/schema [:vector {:min 1 :max 4}
                         [:vector {:min 1 :max 8} [:enum "a" "b" "z" "0" "-"]]]}])

(hst/deftrifecta-from-schema ns-base-path-munges
  hive-addon.hot.source/ns->base-path
  {:in [:cat NsName]
   :out :string
   :num-tests 200
   ;; A scalar string out: the schema-derived mutants have nothing to corrupt.
   ;; The hand-written golden below kills the munging mutants instead.
   :mutation false
   :rel (fn [[n] out]
          (and (not (str/includes? out "-"))
               (not (str/includes? out "."))
               (= (count n) (count out))))})

(tri/deftrifecta resource-paths
  hive-addon.hot.source/ns->resource-paths
  {:golden-path "test/golden/hive-addon/hot-source-resource-paths.edn"
   :cases {:simple "hive-carto.carto-init"
           :single "user"
           :deep "a.b-c.d"}
   :mutations [["cljc-first" (fn [n] (vec (reverse (source/ns->resource-paths n))))]
               ["no-munge" (fn [n] [(str n ".clj") (str n ".cljc")])]]})

(defn source-kinds
  "The classification resolve-source answers, minus the machine-specific URL
   and directory, for a namespace of each kind."
  [ns-str]
  (select-keys (source/resolve-source ns-str) [:addon/init-ns :hot/source-kind :hot/reloadable?]))

(tri/deftrifecta resolve-source-kinds
  hive-addon.hot.source-test/source-kinds
  {:golden-path "test/golden/hive-addon/hot-source-kinds.edn"
   :cases {:directory "hive-addon.hot.source"
           :jar "malli.core"
           :absent "no.such.namespace-anywhere"}
   :mutations [["everything-reloadable"
                (fn [n] (assoc (source-kinds n) :hot/reloadable? true))]
               ["jar-is-directory"
                (fn [n] (update (source-kinds n) :hot/source-kind #(if (= :jar %) :directory %)))]]})

(deftest watchable-dirs-is-the-directory-roots-only
  (let [dirs (source/watchable-dirs [{:addon/id "a" :addon/init-ns "hive-addon.hot.source"}
                                     {:addon/id "b" :addon/init-ns "malli.core"}
                                     {:addon/id "c" :addon/init-ns "no.such.ns"}])]
    (is (= 1 (count dirs)))
    (is (str/ends-with? (first dirs) "src")))
  (is (= ["a" "b"] (mapv :addon/id (source/sources [{:addon/id "a" :addon/init-ns "x.y"}
                                                     {:addon/id "b" :addon/init-ns "malli.core"}])))))
